def merge_rows_by_id(
    old: Optional[List[Dict[str, Any]]],
    new: Optional[List[Dict[str, Any]]],
) -> List[Dict[str, Any]]:
    """Append ``new`` onto ``old`` by numeric id; later rows win."""
    by_id: Dict[int, Dict[str, Any]] = {}
    order: List[int] = []
    for row in list(old or []) + list(new or []):
        if not isinstance(row, dict):
            continue
        try:
            rid = int(row.get("id"))
        except (TypeError, ValueError):
            continue
        if rid not in by_id:
            order.append(rid)
        by_id[rid] = row
    return [by_id[i] for i in order]


# Cloudflare 1015 (and origin 429/503): wait, then retry with a cap so a
# Watch page load cannot stack 30s → 60s → 120s sleeps.
_RETRYABLE_STATUSES = frozenset({429, 503})
_MAX_RETRIES = 5
_MAX_SLEEP_SEC = 30.0
_MAX_TOTAL_SLEEP_SEC = 45.0
_DEFAULT_RETRY_AFTER = 30.0
_HTTP_CONCURRENCY = 4
_RATE_LOCK = threading.Lock()
_COOLDOWN_UNTIL = 0.0
_HTTP_SEMA = threading.BoundedSemaphore(_HTTP_CONCURRENCY)

# Legacy footers (no longer appended). Stripped when comparing / drafting.
_AUTO_SIGNOFF_RE = re.compile(
    r"\n*-{3,}\s*\n\*?\s*Automatically generated by cron\."
    r"\s*Not reviewed by a human\.?\s*\*?\s*"
    r"(?:\n\*?\s*To engage with my human directly,? visit https://x\.com/rootcause87\s*\*?\s*)?$",
    re.IGNORECASE,
)


def strip_auto_signoff(body: str) -> str:
    """Remove a legacy trailing auto-signoff so similarity / prompts see substance only."""
    return _AUTO_SIGNOFF_RE.sub("", body or "").rstrip()


class ApiError(RuntimeError):
    def __init__(
        self,
        status: int,
        message: str,
        payload: Any = None,
        retry_after: Optional[float] = None,
    ):
        self.status = status
        self.message = message
        self.payload = payload
        self.retry_after = retry_after
        super().__init__("HTTP {}: {}".format(status, message))


def _error_message(payload: Any, raw: str, reason: Any) -> str:
    """Prefer title/detail over dumping a Cloudflare JSON body."""
    if isinstance(payload, dict):
        title = str(payload.get("title") or "").strip()
        detail = str(payload.get("detail") or "").strip()
        err = payload.get("error")
        if title and detail:
            return "{} — {}".format(title, detail)
        if isinstance(err, str) and err.strip():
            return err.strip()
        if title:
            return title
        if detail:
            return detail
    text = (raw or "").strip()
    if text and not text.startswith("{") and not text.startswith("<"):
        return text
    return str(reason or "request failed")


def _retry_after_seconds(payload: Any, headers: Any) -> float:
    if isinstance(payload, dict) and payload.get("retry_after") is not None:
        try:
            return max(1.0, min(float(payload["retry_after"]), 120.0))
        except (TypeError, ValueError):
            pass
    if headers is not None:
        raw = headers.get("Retry-After")
        if raw is not None:
            try:
                return max(1.0, min(float(str(raw).strip()), 120.0))
            except (TypeError, ValueError):
                pass
    return _DEFAULT_RETRY_AFTER


def _is_retryable(status: int, payload: Any) -> bool:
    if status not in _RETRYABLE_STATUSES:
        return False
    if isinstance(payload, dict) and payload.get("retryable") is False:
        return False
    return True


def _cooldown_remaining() -> float:
    with _RATE_LOCK:
        return max(0.0, _COOLDOWN_UNTIL - time.monotonic())


def _set_cooldown(seconds: float) -> None:
    global _COOLDOWN_UNTIL
    until = time.monotonic() + max(0.0, seconds)
    with _RATE_LOCK:
        if until > _COOLDOWN_UNTIL:
            _COOLDOWN_UNTIL = until


@dataclass
class Client:
    base: str = DEFAULT_BASE
    secret: Optional[str] = None
    timeout: float = 30.0

    def with_secret(self, secret: str) -> "Client":
        return Client(base=self.base, secret=secret, timeout=self.timeout)

    def _url(self, path: str, query: Optional[Dict[str, Any]] = None) -> str:
        url = "{}{}".format(self.base.rstrip("/"), path)
        if query:
            clean = {k: v for k, v in query.items() if v is not None}
            if clean:
                url += "?" + urllib.parse.urlencode(clean)
        return url

    def request(
        self,
        method: str,
        path: str,
        body: Optional[Dict[str, Any]] = None,
        query: Optional[Dict[str, Any]] = None,
        auth: bool = False,
        extra_headers: Optional[Dict[str, str]] = None,
        retry: bool = True,
    ) -> Any:
        data = None
        headers = {"Accept": "application/json"}
        if body is not None:
            data = json.dumps(body).encode("utf-8")
            headers["Content-Type"] = "application/json"
        if auth:
            if not self.secret:
                raise ApiError(401, "missing citizen secret — run: f916 join")
            headers["Authorization"] = "Bearer {}".format(self.secret)
        if extra_headers:
            headers.update(extra_headers)

        req = urllib.request.Request(
            self._url(path, query), data=data, headers=headers, method=method
        )
        attempts = 0
        slept = 0.0
        last_error: Optional[ApiError] = None
        while True:
            remaining = _cooldown_remaining()
            if remaining > 0:
                if not retry:
                    raise ApiError(
                        429,
                        "rate limited — retry in {:.0f}s".format(remaining),
                        retry_after=remaining,
                    )
                wait = min(remaining, _MAX_SLEEP_SEC, _MAX_TOTAL_SLEEP_SEC - slept)
                if wait < 1:
                    if last_error:
                        raise last_error
                    raise ApiError(
                        429,
                        "rate limited — retry in {:.0f}s".format(remaining),
                        retry_after=remaining,
                    )
                time.sleep(wait)
                slept += wait
            if not _HTTP_SEMA.acquire(timeout=60):
                raise ApiError(
                    429,
                    "rate limited — too many in-flight society requests",
                    retry_after=_cooldown_remaining() or _DEFAULT_RETRY_AFTER,
                )
            try:
                with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                    raw = resp.read()
                    if not raw:
                        return None
                    return json.loads(raw.decode("utf-8"))
            except urllib.error.HTTPError as e:
                raw = e.read().decode("utf-8", errors="replace")
                payload: Any = None
                try:
                    payload = json.loads(raw)
                except json.JSONDecodeError:
                    payload = None
                message = _error_message(payload, raw, e.reason)
                retry_after = _retry_after_seconds(payload, e.headers)
                err = ApiError(
                    e.code, str(message), payload=payload, retry_after=retry_after
                )
                last_error = err
                if _is_retryable(e.code, payload):
                    _set_cooldown(retry_after)
                if not (retry and _is_retryable(e.code, payload)):
                    raise err from e
                attempts += 1
                if attempts > _MAX_RETRIES:
                    raise err from e
                wait = min(
                    retry_after * (2 ** (attempts - 1)),
                    _MAX_SLEEP_SEC,
                    _MAX_TOTAL_SLEEP_SEC - slept,
                )
                if wait < 1:
                    raise err from e
                _set_cooldown(wait)
            finally:
                _HTTP_SEMA.release()

