    def attest_full(
        self,
        *,
        identity_expect: Optional[str] = None,
        ledger_expect: Optional[str] = None,
        max_pages: int = 32,
    ) -> Dict[str, Any]:
        """Follow next_from while status is incomplete; merge expect checks.

        Returns the last page payload plus ``pages`` and ``expect_checks``.
        """
        identity_from: Optional[int] = 0
        ledger_from: Optional[int] = 0
        pages: List[Dict[str, Any]] = []
        last: Dict[str, Any] = {}
        for _ in range(max_pages):
            page = (
                self.attest(
                    identity_from=identity_from,
                    ledger_from=ledger_from,
                    identity_expect=identity_expect if not pages else None,
                    ledger_expect=ledger_expect if not pages else None,
                )
                or {}
            )
            if not isinstance(page, dict):
                break
            pages.append(page)
            last = page
            ident = page.get("identity_log") or {}
            treas = page.get("treasury") or {}
            ident_incomplete = str(ident.get("status") or "") == "incomplete"
            treas_incomplete = str(treas.get("status") or "") == "incomplete"
            if not ident_incomplete and not treas_incomplete:
                break
            nxt_i = page.get("next_identity_from")
            nxt_l = page.get("next_ledger_from")
            # Door: follow next_from while incomplete.
            if nxt_i is None and nxt_l is None:
                nxt = page.get("next_from")
                if isinstance(nxt, dict):
                    nxt_i = nxt.get("identity_from") or nxt.get("identity")
                    nxt_l = nxt.get("ledger_from") or nxt.get("ledger")
                elif nxt is not None:
                    nxt_i = nxt
                    nxt_l = nxt
            advanced = False
            if ident_incomplete and nxt_i is not None:
                identity_from = int(nxt_i)
                advanced = True
            if treas_incomplete and nxt_l is not None:
                ledger_from = int(nxt_l)
                advanced = True
            if not advanced:
                break

        expect_checks: Dict[str, Any] = {}
        if identity_expect or ledger_expect:
            check = (
                self.attest(
                    identity_expect=identity_expect,
                    ledger_expect=ledger_expect,
                )
                or {}
            )
            expect_checks = {
                "identity_expect": identity_expect,
                "ledger_expect": ledger_expect,
                "identity_log": (check.get("identity_log") if isinstance(check, dict) else None),
                "treasury": (check.get("treasury") if isinstance(check, dict) else None),
                "raw": check,
            }

        out = dict(last)
        out["pages"] = len(pages)
        out["expect_checks"] = expect_checks
        return out

